-- Merchants are the tenants: every order, statement and dispute belongs to exactly one.
CREATE TABLE merchant (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(200) NOT NULL,
    slug          VARCHAR(80)  NOT NULL,
    contact_email VARCHAR(254),
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_merchant_slug UNIQUE (slug)
);

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(150) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(16)  NOT NULL,
    merchant_id   BIGINT REFERENCES merchant (id) ON DELETE RESTRICT,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_app_user_username UNIQUE (username),
    CONSTRAINT ck_app_user_role CHECK (role IN ('MERCHANT', 'STAFF')),
    -- A merchant user always has a merchant; staff never do. The database guarantees it,
    -- so the code never has to handle "merchant user without a merchant".
    CONSTRAINT ck_app_user_role_merchant CHECK (
        (role = 'MERCHANT' AND merchant_id IS NOT NULL) OR (role = 'STAFF' AND merchant_id IS NULL)
    )
);

CREATE INDEX idx_app_user_merchant ON app_user (merchant_id);
