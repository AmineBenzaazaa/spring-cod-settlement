-- A courier's settlement file for one merchant over a period.
CREATE TABLE remittance_statement (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id       BIGINT       NOT NULL REFERENCES merchant (id) ON DELETE RESTRICT,
    courier_id        BIGINT       NOT NULL REFERENCES courier (id) ON DELETE RESTRICT,
    period_start      DATE         NOT NULL,
    period_end        DATE         NOT NULL,
    original_filename VARCHAR(255),
    file_sha256       VARCHAR(64)  NOT NULL,
    currency          VARCHAR(3)   NOT NULL DEFAULT 'MAD',
    status            VARCHAR(16)  NOT NULL,
    error_message     TEXT,
    line_count        INTEGER      NOT NULL DEFAULT 0,
    uploaded_by_id    BIGINT REFERENCES app_user (id) ON DELETE SET NULL,
    uploaded_at       TIMESTAMPTZ  NOT NULL,
    reconciled_at     TIMESTAMPTZ,
    -- Idempotency: re-uploading byte-identical content is a no-op. Scoped per merchant so
    -- one tenant can never detect that another tenant uploaded the same file.
    CONSTRAINT uq_statement_merchant_sha256 UNIQUE (merchant_id, file_sha256),
    CONSTRAINT ck_statement_period CHECK (period_end >= period_start),
    CONSTRAINT ck_statement_status CHECK (status IN ('UPLOADED', 'PROCESSING', 'RECONCILED', 'FAILED'))
);

CREATE INDEX idx_statement_courier ON remittance_statement (courier_id);
CREATE INDEX idx_statement_uploaded_at ON remittance_statement (uploaded_at);

-- Raw uploaded bytes, kept apart so listing statements never loads file content.
-- Stored in PostgreSQL (files are capped at a few MB) so the async processor and any
-- other app instance can read them without a shared volume.
CREATE TABLE remittance_statement_file (
    statement_id BIGINT  PRIMARY KEY REFERENCES remittance_statement (id) ON DELETE CASCADE,
    content      BYTEA   NOT NULL,
    size_bytes   INTEGER NOT NULL
);

-- Sequences with INCREMENT 50 match allocationSize = 50 in the entities: Hibernate reserves
-- 50 ids per round trip, which lets it batch the inserts (IDENTITY columns cannot be batched).
CREATE SEQUENCE remittance_line_seq INCREMENT BY 50;

-- One row of the courier CSV: a parcel, the cash collected and the fee withheld.
CREATE TABLE remittance_line (
    id               BIGINT        PRIMARY KEY,
    statement_id     BIGINT        NOT NULL REFERENCES remittance_statement (id) ON DELETE CASCADE,
    row_number       INTEGER       NOT NULL CHECK (row_number > 0),
    tracking_number  VARCHAR(64)   NOT NULL,
    amount_collected NUMERIC(12, 2) NOT NULL,
    fee              NUMERIC(12, 2) NOT NULL,
    order_id         BIGINT REFERENCES orders (id) ON DELETE SET NULL,
    CONSTRAINT uq_line_statement_tracking UNIQUE (statement_id, tracking_number)
);

CREATE INDEX idx_line_order ON remittance_line (order_id);

CREATE SEQUENCE reconciliation_result_seq INCREMENT BY 50;

-- Outcome of reconciling one line and/or one order of a statement.
CREATE TABLE reconciliation_result (
    id               BIGINT        PRIMARY KEY,
    statement_id     BIGINT        NOT NULL REFERENCES remittance_statement (id) ON DELETE CASCADE,
    outcome          VARCHAR(32)   NOT NULL,
    line_id          BIGINT REFERENCES remittance_line (id) ON DELETE CASCADE,
    order_id         BIGINT REFERENCES orders (id) ON DELETE CASCADE,
    tracking_number  VARCHAR(64)   NOT NULL,
    expected_amount  NUMERIC(12, 2) NOT NULL,
    collected_amount NUMERIC(12, 2) NOT NULL,
    difference       NUMERIC(12, 2) NOT NULL,
    created_at       TIMESTAMPTZ   NOT NULL,
    CONSTRAINT uq_result_line UNIQUE (line_id),
    CONSTRAINT ck_result_outcome CHECK (outcome IN ('MATCHED', 'AMOUNT_MISMATCH', 'UNKNOWN_TRACKING', 'MISSING_FROM_STATEMENT'))
);

CREATE INDEX idx_result_statement_outcome ON reconciliation_result (statement_id, outcome);
CREATE INDEX idx_result_order ON reconciliation_result (order_id);
