-- A merchant contesting a reconciliation discrepancy with the courier.
CREATE TABLE dispute (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- RESTRICT: results under dispute can never be deleted, so re-running reconciliation
    -- on a disputed statement fails at the database level too (defence in depth).
    result_id       BIGINT        NOT NULL REFERENCES reconciliation_result (id) ON DELETE RESTRICT,
    -- Denormalised from result -> statement -> merchant for fast tenant filtering and exports.
    merchant_id     BIGINT        NOT NULL REFERENCES merchant (id) ON DELETE RESTRICT,
    reason          TEXT          NOT NULL,
    claimed_amount  NUMERIC(12, 2) NOT NULL,
    status          VARCHAR(16)   NOT NULL,
    resolution_note TEXT,
    opened_by_id    BIGINT REFERENCES app_user (id) ON DELETE SET NULL,
    created_at      TIMESTAMPTZ   NOT NULL,
    resolved_at     TIMESTAMPTZ,
    version         BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uq_dispute_result UNIQUE (result_id),
    CONSTRAINT ck_dispute_claimed_non_negative CHECK (claimed_amount >= 0),
    CONSTRAINT ck_dispute_status CHECK (status IN ('OPEN', 'RESOLVED', 'REJECTED'))
);

CREATE INDEX idx_dispute_merchant_status ON dispute (merchant_id, status);
