-- Last-mile delivery companies that collect cash at the customer's door.
CREATE TABLE courier (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(120) NOT NULL,
    code          VARCHAR(40)  NOT NULL,
    contact_phone VARCHAR(30),
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_courier_name UNIQUE (name),
    CONSTRAINT uq_courier_code UNIQUE (code)
);

-- "order" is a reserved word, hence "orders".
CREATE TABLE orders (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id     BIGINT        NOT NULL REFERENCES merchant (id) ON DELETE RESTRICT,
    courier_id      BIGINT        NOT NULL REFERENCES courier (id) ON DELETE RESTRICT,
    tracking_number VARCHAR(64)   NOT NULL,
    customer_name   VARCHAR(200)  NOT NULL,
    customer_phone  VARCHAR(30),
    city            VARCHAR(100),
    amount_due      NUMERIC(12, 2) NOT NULL,
    currency        VARCHAR(3)    NOT NULL DEFAULT 'MAD',
    status          VARCHAR(16)   NOT NULL,
    delivered_at    TIMESTAMPTZ,
    created_at      TIMESTAMPTZ   NOT NULL,
    updated_at      TIMESTAMPTZ   NOT NULL,
    version         BIGINT        NOT NULL DEFAULT 0,
    -- Tracking numbers are generated by each courier, so they are only unique per courier.
    CONSTRAINT uq_orders_courier_tracking UNIQUE (courier_id, tracking_number),
    CONSTRAINT ck_orders_amount_due_non_negative CHECK (amount_due >= 0),
    CONSTRAINT ck_orders_status CHECK (status IN ('PENDING', 'SHIPPED', 'DELIVERED', 'RETURNED', 'CANCELLED'))
);

CREATE INDEX idx_orders_merchant_courier_status ON orders (merchant_id, courier_id, status);
CREATE INDEX idx_orders_delivered_at ON orders (delivered_at);
CREATE INDEX idx_orders_created_at ON orders (created_at);

CREATE TABLE delivery_attempt (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT      NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    attempted_at TIMESTAMPTZ NOT NULL,
    outcome      VARCHAR(16) NOT NULL,
    note         VARCHAR(255),
    CONSTRAINT ck_delivery_attempt_outcome CHECK (outcome IN ('DELIVERED', 'NO_ANSWER', 'REFUSED', 'RESCHEDULED', 'RETURNED'))
);

CREATE INDEX idx_delivery_attempt_order ON delivery_attempt (order_id);
